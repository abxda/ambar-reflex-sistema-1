ACCENTS = {"á": "a", "é": "e", "í": "i", "ó": "o", "ú": "u", "Á": "A", "É": "E", "Í": "I", "Ó": "O", "Ú": "U",
           "ñ": "n", "Ñ": "N", "ü": "u", "—": "-", "–": "-", "×": "x", "·": ".", "°": "*",}

_cache: dict = {}


def _glyph(ch: str, color, scale: int) -> pygame.Surface:
    key = (ch, color, scale)
    if key in _cache:
        return _cache[key]
    base = ACCENTS.get(ch, ch)
    bits = G.get(base) or G.get(base.upper(), G["?"])
    bits = (bits + "." * 35)[:35]
    surf = pygame.Surface((6 * scale, 9 * scale), pygame.SRCALPHA)
    for i, b in enumerate(bits):
        if b == "#":
            surf.fill(color, ((i % 5) * scale, (2 + i // 5) * scale, scale, scale))
    if ch in "áéíóúÁÉÍÓÚ":
        surf.fill(color, (3 * scale, 0, scale, scale))
        surf.fill(color, (2 * scale, scale, scale, scale))
    if ch in "ñÑ":
        surf.fill(color, (1 * scale, 0, 3 * scale, scale))
    _cache[key] = surf
    return surf


def draw(surface: pygame.Surface, text: str, x: int, y: int, color=(255, 176, 0), scale: int = 1, alpha: int = 255) -> int:
    """Draw text; returns the x after the last glyph. Each glyph cell is 6x9 at scale 1."""
    for ch in text:
        g = _glyph(ch, color, scale)
        if alpha < 255:
            g = g.copy()
            g.set_alpha(alpha)
        surface.blit(g, (x, y))
        x += 6 * scale
    return x


def width(text: str, scale: int = 1) -> int:
    return len(text) * 6 * scale
